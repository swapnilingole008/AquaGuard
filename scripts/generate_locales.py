def translate_obj(obj, lang_code):
    """
    Translates every key in obj recursively for the given lang_code.
    1. Checks TRANSLATIONS[lang_code]
    2. Checks GLOSSARY[lang_code]
    3. Checks Hindi as an Indic fallback with dialect overrides
    """
    if lang_code in TRANSLATIONS:
        # We already have complete curated translations
        res = {}
        for section, sec_data in obj.items():
            res[section] = {}
            for k, en_val in sec_data.items():
                res[section][k] = TRANSLATIONS[lang_code].get(section, {}).get(k, en_val)
        return res

    gloss = GLOSSARY.get(lang_code, {})
    hi_dict = TRANSLATIONS["hi"]
    dialect_overrides = FALLBACK_DIALECTS.get(lang_code, {})
    
    # Synthesize complete dictionary
    res = {}
    for section, sec_data in obj.items():
        res[section] = {}
        for k, en_val in sec_data.items():
            # Priority 1: Exact gloss match
            if en_val in gloss:
                res[section][k] = gloss[en_val]
            # Priority 2: Dialect overrides (e.g. navigation labels)
            elif en_val in dialect_overrides:
                res[section][k] = dialect_overrides[en_val]
            # Priority 3: For Urdu-derived (ks, sd), fallback to urdu
            elif lang_code in ("ks", "sd") and "ur" in GLOSSARY and en_val in GLOSSARY["ur"]:
                res[section][k] = GLOSSARY["ur"][en_val]
            # Priority 4: For Sanskrit / Maithili / Dogri / Nepali / Konkani, use Hindi terms with high affinity
            elif lang_code in ("sa", "mai", "doi", "ne", "kok", "brx", "sat", "mni"):
                hi_val = hi_dict.get(section, {}).get(k, en_val)
                res[section][k] = hi_val
            else:
                # Default to Hindi translation for maximum comprehension across India, or english
                res[section][k] = hi_dict.get(section, {}).get(k, en_val)
    return res

def write_locale_file(lang_code, data):
    target_path = os.path.join("src", "i18n", "locales", f"{lang_code}.js")
    js_content = f"// AgriGuard Locale: {LANG_METADATA.get(lang_code, {}).get('name', lang_code)} ({LANG_METADATA.get(lang_code, {}).get('native', '')})\n"
    js_content += "export default " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
    with open(target_path, "w", encoding="utf-8") as f:
        f.write(js_content)
    print(f"Generated {target_path} (keys: {sum(len(v) for v in data.values())})")

